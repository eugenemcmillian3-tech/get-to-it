#!/usr/bin/env node
/**
 * Writes supabase/schema.snapshot.json by replaying the migrations into an
 * embedded Postgres and reading back its policies, constraints and indexes.
 *
 * The snapshot is what `npm run check:schema-drift` compares a live database
 * against, so it must be regenerated whenever a migration changes one of those
 * objects. `npm run test:knowledge` fails when the committed snapshot is stale.
 *
 * Usage: npm run schema:snapshot
 */

import { rm, writeFile } from "node:fs/promises";
import path from "node:path";
import EmbeddedPostgres from "embedded-postgres";
import pg from "pg";
import { collectCatalog } from "./schema-catalog.mjs";

const DATA_DIR = path.join(process.cwd(), ".schema-snapshot-data");
const PORT = Number(process.env.SCHEMA_SNAPSHOT_PORT ?? 55441);
const DATABASE = "knowledge_test";
const OUTPUT = path.join(process.cwd(), "supabase/schema.snapshot.json");

async function bootstrap(client) {
  await client.query(`
    do $$
    begin
      if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
      if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
      if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
    end $$;
  `);
  await client.query(`
    alter default privileges in schema public grant select, insert, update, delete on tables to authenticated;
    alter default privileges in schema public grant select on tables to anon;
    alter default privileges in schema public grant usage, select on sequences to authenticated;
    alter default privileges in schema public grant execute on functions to anon, authenticated;
  `);
  await client.query("create schema if not exists auth");
  await client.query(`
    create table if not exists auth.users (
      id uuid primary key default gen_random_uuid(),
      email text unique,
      instance_id uuid,
      aud text default 'authenticated',
      role text default 'authenticated',
      raw_user_meta_data jsonb default '{}'::jsonb,
      raw_app_meta_data jsonb default '{}'::jsonb,
      email_confirmed_at timestamptz,
      last_sign_in_at timestamptz,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
  `);
  await client.query(`
    create or replace function auth.uid() returns uuid language sql stable as $fn$
      select ((nullif(current_setting('request.jwt.claims', true), '')::jsonb) ->> 'sub')::uuid
    $fn$;
    create or replace function auth.role() returns text language sql stable as $fn$
      select coalesce(((nullif(current_setting('request.jwt.claims', true), '')::jsonb) ->> 'role'), 'authenticated')
    $fn$;
    grant usage on schema auth to anon, authenticated;
    grant execute on function auth.uid() to anon, authenticated;
    grant execute on function auth.role() to anon, authenticated;
  `);
}

async function main() {
  const server = new EmbeddedPostgres({
    databaseDir: DATA_DIR,
    user: "postgres",
    password: "postgres",
    port: PORT,
    persistent: false,
  });
  let started = false;
  try {
    await rm(DATA_DIR, { recursive: true, force: true });
    await server.initialise();
    await server.start();
    started = true;
    await server.createDatabase(DATABASE);

    const client = new pg.Client({
      connectionString: `postgresql://postgres:postgres@127.0.0.1:${PORT}/${DATABASE}`,
    });
    await client.connect();
    try {
      await bootstrap(client);
      const files = (await import("node:fs/promises")).readdir
        ? (await (await import("node:fs/promises")).readdir(path.join(process.cwd(), "supabase/migrations")))
            .filter((name) => name.endsWith(".sql"))
            .sort()
        : [];
      for (const file of files) {
        const sql = await (await import("node:fs/promises")).readFile(
          path.join(process.cwd(), "supabase/migrations", file),
          "utf8",
        );
        await client.query(sql);
      }
      const catalog = await collectCatalog(client);
      const { version } = (await client.query("select version() as version")).rows[0];
      const payload = {
        note: "Generated by npm run schema:snapshot from supabase/migrations. Do not edit by hand.",
        generatedWith: version,
        ...catalog,
      };
      await writeFile(OUTPUT, JSON.stringify(payload, null, 2) + "\n");
      console.log(
        `wrote ${OUTPUT}: ${catalog.policies.length} policies, ${catalog.constraints.length} constraints, ${catalog.indexes.length} indexes`,
      );
    } finally {
      await client.end();
    }
  } finally {
    if (started) {
      try {
        await server.stop();
      } catch (error) {
        console.error("Could not stop the snapshot database:", error.message);
      }
    }
    await rm(DATA_DIR, { recursive: true, force: true });
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
