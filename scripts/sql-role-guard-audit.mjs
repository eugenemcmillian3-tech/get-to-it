#!/usr/bin/env node
/**
 * Finds role guards that silently pass when the caller has no role.
 *
 * `v_role not in ('owner','admin')` is NULL, not false, when the caller has no
 * role, so `if ... then raise` never runs. That shipped in the Phase 37
 * knowledge functions (fixed by 0052) and in the Phase 28 build room (fixed by
 * 0054). The same scan generated 0054, so the check and the fix cannot drift.
 *
 * Usage:
 *   node scripts/sql-role-guard-audit.mjs            # exit 1 if any remain
 *   node scripts/sql-role-guard-audit.mjs --emit f   # write the fix migration
 *
 * It reads the latest definition of each function across supabase/migrations,
 * because that is the schema the project would actually deploy.
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const MIGRATIONS = path.join(process.cwd(), "supabase/migrations");
const ROLE_WORDS = ["owner", "admin", "maintainer", "member", "contributor", "reviewer", "viewer"];
const DEFINITION =
  /create or replace function (public\.[a-z_0-9]+)\s*\(([\s\S]*?)\)\s*returns[\s\S]*?\$\$([\s\S]*?)\$\$;/g;

function collect() {
  const latest = new Map();
  for (const file of readdirSync(MIGRATIONS).filter((name) => name.endsWith(".sql")).sort()) {
    const sql = readFileSync(path.join(MIGRATIONS, file), "utf8");
    for (const match of sql.matchAll(DEFINITION)) {
      latest.set(match[1], { file, full: match[0], args: match[2], body: match[3] });
    }
  }
  return latest;
}

function isRoleGuard(variable, values) {
  return (
    variable.startsWith("v_role") ||
    variable.startsWith("v_actor_role") ||
    variable.startsWith("p_role") ||
    ROLE_WORDS.some((word) => values.includes(word))
  );
}

/** Guard sites where a null role would fall straight through. */
function analyse({ body }) {
  const findings = [];
  for (const match of body.matchAll(/if\s+([a-z_]\w*)\s+not in\s*\(([^)]*)\)/g)) {
    const [, variable, values] = match;
    if (!isRoleGuard(variable, values)) continue;

    const prefix = body.slice(0, match.index);
    if (new RegExp(`\\b${variable}\\s+is null`).test(prefix)) continue;

    // A variable that is coalesced when it is set can never be null here.
    const assignments = [...prefix.matchAll(new RegExp(`\\b${variable}\\b[^;]*?:=\\s*([^;]*);`, "g"))];
    const last = assignments.at(-1)?.[1] ?? "";
    if (last.toLowerCase().includes("coalesce(")) continue;

    findings.push({ variable, guard: match[0].trim(), index: match.index });
  }
  return findings;
}

function patch(definition) {
  const findings = analyse(definition);
  let full = definition.full;
  const bodyStart = full.indexOf(definition.body);
  for (const finding of [...findings].sort((a, b) => b.index - a.index)) {
    const at = bodyStart + finding.index;
    const replacement = finding.guard.replace(
      `if ${finding.variable} not in`,
      `if ${finding.variable} is null or ${finding.variable} not in`,
    );
    full = full.slice(0, at) + replacement + full.slice(at + finding.guard.length);
  }
  // `app_project_role(...) <> 'owner'` has the same NULL problem.
  const inequality = /if\s+(public\.app_project_role\([^)]*\))\s*<>\s*'owner'\s+then/g;
  full = full.replace(inequality, "if $1 is distinct from 'owner' then");
  return { full, findings };
}

const emitIndex = process.argv.indexOf("--emit");
const emitTo = emitIndex === -1 ? null : process.argv[emitIndex + 1];
const latest = collect();
const changed = [];
for (const [name, definition] of [...latest].sort(([a], [b]) => a.localeCompare(b))) {
  const { full, findings } = patch(definition);
  if (full !== definition.full) changed.push({ name, file: definition.file, findings, full });
}

if (emitTo) {
  const header = `-- GET TO IT — reject a caller with no role, in the Phase 28 build room.
--
-- \`v_role not in ('owner', 'admin')\` is NULL, not false, when the caller has no
-- role at all, so the guard never fired. The same defect was found and fixed in
-- the Phase 37 knowledge functions (0052). Before this migration a non-member
-- could create or cancel a build task, review, merge or rebase a changeset, and
-- link their own project into a workspace they do not belong to.
--
-- Every guard now tests for a null role first, and the workspace link uses
-- \`is distinct from 'owner'\` instead of \`<> 'owner'\`. The functions are
-- otherwise unchanged: each is redefined here from its latest definition.
--
-- Generated by scripts/sql-role-guard-audit.mjs --emit, so the audit and this
-- fix share one rule set.

`;
  writeFileSync(emitTo, header + changed.map((entry) => entry.full).join("\n\n") + "\n");
  console.log(`wrote ${emitTo}: ${changed.length} functions, ${changed.reduce((n, c) => n + c.findings.length, 0)} guard sites`);
  for (const entry of changed) {
    for (const finding of entry.findings) {
      console.log(`  ${entry.name}: ${finding.guard} -> ${finding.guard.replace(`if ${finding.variable} not in`, `if ${finding.variable} is null or ${finding.variable} not in`)}`);
    }
    if (!entry.findings.length) console.log(`  ${entry.name}: app_project_role(...) <> 'owner' NULL fix`);
  }
  process.exit(0);
}

if (changed.length > 0) {
  const sites = changed.reduce((total, entry) => total + entry.findings.length, 0);
  console.error(`✖ ${sites} role guard(s) can pass when the caller has no role, in ${changed.length} function(s):`);
  for (const entry of changed) {
    console.error(`  ${entry.file} :: ${entry.name}`);
    for (const finding of entry.findings) console.error(`      ${finding.guard}`);
  }
  console.error("Add `is null or`, or check the role for null before it.");
  process.exit(1);
}

console.log(`✔ ${latest.size} functions scanned; every role guard rejects a null role.`);
