#!/usr/bin/env node
/**
 * Finds authorization guards that silently pass when the caller has no role.
 *
 * `v_role not in ('owner','admin')` is NULL, not false, when the caller has no
 * role, so `if ... then raise` never runs. The first version of this scan only
 * matched guards that began with the variable, which hid two shapes:
 *
 *   - compound conditions: `if p_kind = 'agent' and v_role not in (...)` and
 *   - role lookups: `if public.workspace_role(id) not in ('owner','admin')`,
 *     where the function returns NULL for a caller who is not a member.
 *
 * Both are scanned now. 0052 fixed the Phase 37 knowledge functions, 0054 the
 * Phase 28 build room, and 0055 these two shapes. Every migration here was
 * generated by this script, so the check and the fixes cannot drift.
 *
 * Usage:
 *   node scripts/sql-role-guard-audit.mjs            # exit 1 if any remain
 *   node scripts/sql-role-guard-audit.mjs --emit f   # write the fix migration
 *
 * It reads the latest definition of each function across supabase/migrations,
 * because that is the schema the project would actually deploy.
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const MIGRATIONS = path.join(process.cwd(), "supabase/migrations");
const ROLE_FUNCTION = /public\.(?:app_project_role|workspace_role)\s*\(/;
const ROLE_NAME = /(?:^|_)(?:actor_)?role$/;
const DEFINITION =
  /create or replace function (public\.[a-z_0-9]+)\s*\(([\s\S]*?)\)\s*returns[\s\S]*?\$\$([\s\S]*?)\$\$;/g;

function collect() {
  const latest = new Map();
  for (const file of readdirSync(MIGRATIONS).filter((name) => name.endsWith(".sql")).sort()) {
    const sql = readFileSync(path.join(MIGRATIONS, file), "utf8");
    for (const match of sql.matchAll(DEFINITION)) {
      latest.set(match[1], { file, full: match[0], args: match[2], body: match[3] });
    }
  }
  return latest;
}

/** The expression immediately before `not in`, which may be a call like `f(x)`. */
function operandBefore(text, index) {
  let end = index;
  while (end > 0 && /\s/.test(text[end - 1])) end -= 1;
  let start = end;
  if (text[end - 1] === ")") {
    let depth = 0;
    for (let i = end - 1; i >= 0; i -= 1) {
      if (text[i] === ")") depth += 1;
      else if (text[i] === "(") {
        depth -= 1;
        if (depth === 0) {
          start = i;
          break;
        }
      }
    }
    while (start > 0 && /[\w.]/.test(text[start - 1])) start -= 1;
  } else {
    while (start > 0 && /[\w.]/.test(text[start - 1])) start -= 1;
  }
  return { operand: text.slice(start, end), start };
}

function isRoleGuard(operand) {
  const bare = operand.replace(/\s*\([\s\S]*$/, "");
  return ROLE_NAME.test(bare) || ROLE_FUNCTION.test(operand);
}

/** True when the operand cannot be null at this point in the body. */
function rejectsNull(body, condition, operand, index) {
  const escaped = operand.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  if (/[^\w.]coalesce\s*\(|^coalesce\s*\(/i.test(operand)) return true;
  if (new RegExp(`${escaped}\\s+is null`, "i").test(condition)) return true;

  const prefix = body.slice(0, index);
  if (new RegExp(`${escaped}\\s+is null`, "i").test(prefix)) return true;

  if (!operand.includes("(")) {
    const assignments = [...prefix.matchAll(new RegExp(`\\b${escaped}\\b[^;]*?:=\\s*([^;]*);`, "g"))];
    const last = assignments.at(-1)?.[1] ?? "";
    if (/coalesce\s*\(/i.test(last)) return true;
  }
  return false;
}

/** Guard sites where a null role would fall straight through. */
function analyse({ body }) {
  const findings = [];
  for (const statement of body.matchAll(/\bif\b([\s\S]*?)\bthen\b/g)) {
    const condition = statement[1];
    if (!/not in\s*\(/i.test(condition)) continue;
    for (const site of condition.matchAll(/not in\s*\(/gi)) {
      const { operand, start } = operandBefore(condition, site.index);
      if (!operand || !isRoleGuard(operand)) continue;
      const conditionStart = statement.index + statement[0].indexOf(condition);
      const absolute = conditionStart + start;
      if (rejectsNull(body, condition, operand, absolute)) continue;
      findings.push({ operand, index: absolute, condition: condition.trim().replace(/\s+/g, " ") });
    }
  }
  return findings;
}

/** Wraps each nullable guard as `(x is null or x not in (...))`, parens included. */
function patch(definition) {
  const findings = analyse(definition);
  let full = definition.full;
  const bodyStart = full.indexOf(definition.body);
  for (const finding of [...findings].sort((a, b) => b.index - a.index)) {
    const at = bodyStart + finding.index;
    const rest = full.slice(at);
    const open = rest.indexOf("(", finding.operand.length);
    let depth = 0;
    let close = -1;
    for (let i = open; i < rest.length; i += 1) {
      if (rest[i] === "(") depth += 1;
      else if (rest[i] === ")") {
        depth -= 1;
        if (depth === 0) {
          close = i;
          break;
        }
      }
    }
    if (close === -1) continue;
    const site = rest.slice(0, close + 1); // `x not in (...)`
    full = full.slice(0, at) + `(${finding.operand} is null or ${site})` + full.slice(at + close + 1);
  }
  // `app_project_role(...) <> 'owner'` has the same NULL problem.
  const inequality = /if\s+(public\.app_project_role\([^)]*\))\s*<>\s*'owner'\s+then/g;
  full = full.replace(inequality, "if $1 is distinct from 'owner' then");
  return { full, findings };
}

const emitIndex = process.argv.indexOf("--emit");
const emitTo = emitIndex === -1 ? null : process.argv[emitIndex + 1];
const latest = collect();
const changed = [];
for (const [name, definition] of [...latest].sort(([a], [b]) => a.localeCompare(b))) {
  const { full, findings } = patch(definition);
  if (full !== definition.full) changed.push({ name, file: definition.file, findings, full });
}

if (emitTo) {
  const header = `-- GET TO IT — reject a caller whose role lookup came back empty.
--
-- Two guard shapes were still NULL-unsafe after 0052 and 0054:
--
--   if public.workspace_role(id) not in ('owner', 'admin') then ...
--   if p_kind = 'agent' and v_role not in ('owner', 'maintainer') then ...
--
-- A role lookup returns NULL for a caller who is not a member, and a compound
-- condition is NULL when its role half is NULL, so neither guard fired. A
-- stranger could create a changeset or a share link in any project, and any
-- signed-in user could claim, finish, cancel or recover another workspace's
-- mission-control jobs, or decide its approvals. Every guard now tests its role
-- source for null first, parenthesised so compound precedence is unchanged.
--
-- Each function is redefined from its latest definition and is otherwise
-- unchanged. Generated by scripts/sql-role-guard-audit.mjs --emit.

`;
  writeFileSync(emitTo, header + changed.map((entry) => entry.full).join("\n\n") + "\n");
  const sites = changed.reduce((total, entry) => total + entry.findings.length, 0);
  console.log(`wrote ${emitTo}: ${changed.length} functions, ${sites} guard sites`);
  for (const entry of changed) for (const finding of entry.findings) console.log(`  ${entry.name}: ${finding.operand}`);
  process.exit(0);
}

if (changed.length > 0) {
  const sites = changed.reduce((total, entry) => total + entry.findings.length, 0);
  console.error(`✖ ${sites} role guard(s) can pass when the role is null, in ${changed.length} function(s):`);
  for (const entry of changed) {
    console.error(`  ${entry.file} :: ${entry.name}`);
    for (const finding of entry.findings) console.error(`      ${finding.condition}`);
  }
  console.error("Add `is null or`, or check the role for null before it.");
  process.exit(1);
}

console.log(`✔ ${latest.size} functions scanned; every role guard rejects a null role.`);
