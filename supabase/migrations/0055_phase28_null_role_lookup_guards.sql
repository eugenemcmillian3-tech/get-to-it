-- GET TO IT — reject a caller whose role lookup came back empty.
--
-- Two guard shapes were still NULL-unsafe after 0052 and 0054:
--
--   if public.workspace_role(id) not in ('owner', 'admin') then ...
--   if p_kind = 'agent' and v_role not in ('owner', 'maintainer') then ...
--
-- A role lookup returns NULL for a caller who is not a member, and a compound
-- condition is NULL when its role half is NULL, so neither guard fired. A
-- stranger could create a changeset or a share link in any project, and any
-- signed-in user could claim, finish, cancel or recover another workspace's
-- mission-control jobs, or decide its approvals. Every guard now tests its role
-- source for null first, parenthesised so compound precedence is unchanged.
--
-- Each function is redefined from its latest definition and is otherwise
-- unchanged. Generated by scripts/sql-role-guard-audit.mjs --emit.

create or replace function public.cancel_app_changeset(p_changeset_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_changeset public.app_changesets;
  v_role text;
begin
  select * into v_changeset from public.app_changesets where id = p_changeset_id;
  if not found then raise exception 'changeset not found'; end if;
  v_role := public.app_project_role(v_changeset.project_id);
  if v_actor <> v_changeset.author_id and (v_role is null or v_role not in ('owner', 'maintainer')) then
    raise exception 'only the author or a maintainer can cancel this changeset';
  end if;
  if v_changeset.status in ('merged', 'cancelled') then raise exception 'changeset is closed'; end if;

  update public.app_changesets
     set status = 'cancelled', cancelled_at = now(), reviewed_digest = null
   where id = p_changeset_id;
  return jsonb_build_object('ok', true);
end;
$$;

